export function copyFor(language: Language): Copy {
  return language === "zh-CN" ? zh : language === "ja" ? ja : en;
}

export function localizeRuntimeMessage(copy: Copy, message: string, id?: string, language?: Language): string {
  if (language === "en") return message;
  if (id === "proxy") return message.replace("Responses proxy is healthy on ", language === "zh-CN" ? "Responses 代理在 " : "Responses プロキシは ").replace(/ healthy$/, language === "zh-CN" ? " 上运行正常" : " で正常に動作しています");
  if (id === "connector") return message.replace(/^ChatGPT connector /, language === "zh-CN" ? "ChatGPT 连接器 " : "ChatGPT コネクタ ").replace(/ is available$/, language === "zh-CN" ? "可用" : "を利用できます");
  const known: Record<string, string> = language === "zh-CN" ? {
    "tunnel-binary": "已安装固定版本的 openai/tunnel-client 二进制文件",
    "tunnel-key": "隧道运行时密钥已安全存储",
    "tunnel-service": "启动器正在管理隧道运行时",
    "tunnel-runtime": "隧道运行正常，可以使用",
  } : {
    "tunnel-binary": "固定バージョンの openai/tunnel-client バイナリがインストールされています",
    "tunnel-key": "トンネルのランタイムキーは安全に保存されています",
    "tunnel-service": "ランチャーがトンネルランタイムを管理しています",
    "tunnel-runtime": "トンネルランタイムは正常で、使用可能です",
  };
  return id && known[id] ? known[id] : message;
}
